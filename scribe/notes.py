def _apply_session_identity(args) -> None:
    """Fill role/mission/session-id from the session identity where blank.

    Only write commands inherit role/mission — for a read command an absent
    --role means "no filter", and inheriting one would hide every note
    written before identities existed. The session id is filled for handoffs
    regardless, so a hand-written handoff is still attributable.
    """
    default_role, default_mission, default_sid = paths.session_identity()
    if args.command in _WRITE_COMMANDS:
        if hasattr(args, "role") and not getattr(args, "role", ""):
            args.role = default_role
        if hasattr(args, "mission") and not getattr(args, "mission", ""):
            args.mission = default_mission
    if (
        hasattr(args, "session_id")
        and not getattr(args, "session_id", "")
        and getattr(args, "type", "") == "handoff"
    ):
        args.session_id = default_sid


def main():
    parser = build_parser()
    args = parser.parse_args()
    if not args.command:
        parser.print_help()
        return

    # Identity is read only once a command is present, so `--help` works
    # without a valid session identity file.
    _apply_session_identity(args)

    try:
        state_dir = paths.resolve_store_dir(args.project)
    except paths.ProjectKeyError as e:
        die(str(e))
    args.store = ScribeStore(state_dir)

    handler = COMMANDS.get(args.command)
    if handler:
        try:
            handler(args)
        except TimeoutError as e:
            # FileLock gave up: another apiary process (a hook, a second
            # session) is holding an index lock. A traceback here is not an
            # answer; say what to do. `add` writes the body before the row, so
            # a body without a row may be left behind — `repair` reattaches it.
            die(
                f"index busy — could not acquire a scribe lock ({e}). "
                "Retry in a moment; if this was `add`, run `notes.py repair` to "
                "reattach any body written before the lock timed out."
            )
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
