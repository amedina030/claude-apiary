def cmd_add(args):
    store = args.store

    # Idempotency guard for /wrapup: skip when this session already has a
    # handoff. Searches archived too, because "keep only the latest handoff"
    # moves the previous one to the archive almost immediately.
    if getattr(args, "if_no_handoff_for", None):
        try:
            target_sid = SessionId(args.if_no_handoff_for)
        except ValueError as e:
            print(f"Error: {e}", file=sys.stderr)
            return
        for handoff in store.list_notes(note_type="handoff", status="all"):
            if target_sid.matches(handoff.get("session", "")):
                print(
                    f"Handoff for session {target_sid.short} already exists "
                    f"({handoff.get('display_id', _format_id(handoff))}). Skipping."
                )
                return

    content = check_length(content_from_args(args), MAX_CONTENT_LENGTH, "content", unit="bytes")

    summary = (getattr(args, "summary", "") or "").strip()
    if args.type == "handoff" and not summary:
        die(
            "--summary is required for --type handoff. Provide a one-line "
            'abstract (e.g. "Session abc12345: fixed X, decided Y").'
        )
    check_length(summary, MAX_SUMMARY_LENGTH, "--summary")
    brief_summary = (getattr(args, "brief_summary", "") or "").strip()
    check_length(brief_summary, BRIEF_SUMMARY_MAX, "--brief-summary")

    # Template gate: one check, one attempt, --force to bypass. Forward-only —
    # it runs on `add`, never against notes already written.
    message, fatal = templates.gate(
        store.state_dir, args.type, content, force=getattr(args, "force", False)
    )
    if message:
        print(message, file=sys.stderr)
    if fatal:
        sys.exit(1)

    # --unique-tag skips the add (exit 0) when an active note already carries
    # the tag; otherwise the tag is added to this note (spec §5.14).
    tags = tag_list(args)
    unique_tag = (getattr(args, "unique_tag", "") or "").strip()
    if unique_tag:
        existing = store.find_active_with_tag(unique_tag)
        if existing is not None:
            brief = existing.get("brief_summary") or existing.get("summary") or ""
            print(
                f"skipped (active {_format_id(existing)} already carries tag "
                f"'{unique_tag}'): {brief}"
            )
            return
        if unique_tag not in tags:
            tags.append(unique_tag)

    metadata = {}
    if getattr(args, "auto", False):
        metadata["auto_generated"] = True
    if getattr(args, "role", ""):
        metadata["role"] = args.role
    if getattr(args, "mission", ""):
        metadata["mission"] = args.mission
    if tags:
        metadata["tags"] = tags

    entry = store.add_note(
        note_type=args.type,
        content=content,
        session_id=args.session_id or "",
        summary=summary,
        brief_summary=brief_summary,
        **metadata,
    )
    print(f"Added {_format_id(entry)} ({entry['type']})")
    policy.run_auto_archive(store)


def cmd_list(args):
    store = args.store
    if args.archive:
        status, source = "archived", "archive"
    else:
        status, source = ("all" if args.all else "active"), "active"

    # `list` is a read command and does not mutate state. The retention sweep
    # runs from `add`, from session startup, and on demand via `tidy` —
    # listing notes must not make them disappear (Phase 1.5).
    notes_list = store.list_notes(note_type=args.type or None, status=status, search=args.search)

    if getattr(args, "deferred", False):
        notes_list = [n for n in notes_list if n.get("status") == "deferred"]
    elif not args.all and not args.archive:
        notes_list = [
            n for n in notes_list if n.get("status") not in ("done", "dropped", "deferred")
        ]

    if args.session:
        try:
            sid = SessionId(args.session)
        except ValueError as e:
            print(f"Error: {e}", file=sys.stderr)
            return
        notes_list = [n for n in notes_list if sid.matches(n.get("session", ""))]
    notes_list = _by_role_mission(args, notes_list)

    if args.last is not None:
        if args.last <= 0:
            die("--last must be a positive integer")
        notes_list = notes_list[-min(args.last, MAX_LAST) :]

    if not notes_list:
        print(f"No {source} notes found.")
        return
    for entry in notes_list:
        print(formatting.note_line(entry))


def cmd_get(args):
    store = args.store
    note_type, year, seq = _parse_id_arg(args.id)
    is_learning = note_type == "learning"

    if is_learning:
        note = store.get_learning(year, seq)
    else:
        note = store.get_note(note_type, year, seq)
        if note and note.get("_from_archive"):
            print("[from archive]")

    if not note:
        print(f"Note {args.id} not found.", file=sys.stderr)
        sys.exit(1)

    for line in formatting.note_detail(note, is_learning=is_learning):
        print(line)


def _transition(
    args, *, target: str, already: str, blocked_from: tuple = (), blocked_message: str = ""
):
    """Move a note to *target* status, or explain why it cannot move.

    The status verbs (done/drop/defer) differ only in the status they set,
    what they call it, and which prior statuses refuse the move — they were
    three near-identical twenty-line handlers. Returns the updated entry, or
    None when the note was already there.
    """
    store = args.store
    note_type, year, seq = _note_id_arg(args, reject=' — use "unlearn" to remove it')
    note = store.get_note(note_type, year, seq)
    if not note:
        print(f"Note {args.id} not found.", file=sys.stderr)
        sys.exit(1)
    status = note.get("status")
    if status == target:
        print(f"Note {args.id} is already {already}.")
        return None
    if status in blocked_from:
        die(blocked_message.format(id=args.id, status=status))
    return _require_updated(store.update_note(note_type, year, seq, status=target), args.id)


def cmd_done(args):
    updated = _transition(args, target="done", already="marked done")
    if updated is None:
        return
    # External-ticket close signal (spec §5.14 / A2). Non-destructive:
    # surfaces the link for the Asana tool to observe; closes nothing local.
    if updated.get("type") == "todo":
        links = policy.external_ticket_links(updated)
        if links:
            print(
                f"[external ticket link(s) {', '.join(links)}: close observed by the Asana tool]",
                file=sys.stderr,
            )
    print(f"Marked {args.id} as done.")


def cmd_drop(args):
    if (
        _transition(
            args,
            target="dropped",
            already="dropped",
            blocked_from=("done",),
            blocked_message="note {id} is already done; cannot drop.",
        )
        is not None
    ):
        print(f"Marked {args.id} as dropped.")


def cmd_defer(args):
    updated = _transition(
        args,
        target="deferred",
        already="deferred",
        blocked_from=("done", "dropped"),
        blocked_message="note {id} is {status}; cannot defer a closed note.",
    )
    if updated is None:
        return
    where = " (it stays in the archive)" if updated.get("_from_archive") else ""
    print(f'Deferred {args.id}{where}. Use "resume {args.id}" to bring it back.')


def cmd_resume(args):
    store = args.store
    note_type, year, seq = _note_id_arg(args, reject=" and cannot be resumed")
    note = store.get_note(note_type, year, seq)
    if not note:
        print(f"Note {args.id} not found.", file=sys.stderr)
        sys.exit(1)
    if note.get("status") != "deferred":
        print(f"Note {args.id} is not deferred (status: {note.get('status', '?')}).")
        return
    updated = _require_updated(store.update_note(note_type, year, seq, status="active"), args.id)
    if updated.get("_from_archive"):
        # An archived note that becomes active again has to leave the archive,
        # or `list` and the startup banner never show it.
        store.unarchive_note(note_type, year, seq)
        print(f"Resumed {args.id} (moved back out of the archive).")
        return
    print(f"Resumed {args.id}.")


def cmd_unarchive(args):
    note_type, year, seq = _note_id_arg(args, reject=" and does not use archive")
    entry = args.store.unarchive_note(note_type, year, seq)
    if entry is None:
        print(f"Note {args.id} not found in archive.", file=sys.stderr)
        sys.exit(1)
    print(f"Unarchived {args.id} (status preserved: {entry.get('status', '?')}).")


def cmd_update(args):
    if getattr(args, "content_file", None) is not None:
        args.content = content_from_args(args)
    brief_override = (getattr(args, "brief_summary", "") or "").strip()
    add_tags = [t for t in (getattr(args, "add_tag", None) or []) if t]
    remove_tags = [t for t in (getattr(args, "remove_tag", None) or []) if t]
    if (
        args.content is None
        and args.session_id is None
        and not brief_override
        and not add_tags
        and not remove_tags
    ):
        die("provide --content, --session-id, --brief-summary, --add-tag, and/or --remove-tag")
    if args.content is not None:
        check_length(args.content, MAX_CONTENT_LENGTH, "content", unit="bytes")
    check_length(brief_override, BRIEF_SUMMARY_MAX, "--brief-summary")

    store = args.store
    note_type, year, seq = _note_id_arg(args, reject=' — use "unlearn" to remove it')
    note = store.get_note(note_type, year, seq)
    if not note:
        print(f"Note {args.id} not found.", file=sys.stderr)
        sys.exit(1)
    # A done note's content is frozen, but tag/brief/session mutation stays
    # allowed — the Asana tool flips status tags on closed mirrors (spec §5.14).
    if note.get("status") == "done" and args.content is not None:
        die(f"note {args.id} is already done; cannot edit content.")

    kwargs = {}
    if args.content is not None:
        kwargs["content"] = args.content
        kwargs["summary"] = derive_summary(args.content)
    if args.session_id is not None:
        kwargs["session"] = args.session_id
    if brief_override:
        kwargs["brief_summary"] = brief_override
    if add_tags:
        kwargs["add_tags"] = add_tags
    if remove_tags:
        kwargs["remove_tags"] = remove_tags
    _require_updated(store.update_note(note_type, year, seq, **kwargs), args.id)
    print(f"Updated {args.id}.")


def cmd_archive(args):
    store = args.store
    if args.before:
        try:
            cutoff = datetime.strptime(args.before, "%Y-%m-%d").replace(tzinfo=timezone.utc)
        except ValueError:
            die(f"--before must be in YYYY-MM-DD format, got {args.before!r}")
    else:
        cutoff = policy.default_archive_cutoff()

    keys = policy.select_archivable_before(store.list_notes(status="active"), cutoff)
    for note_type, year, seq in keys:
        store.archive_note(note_type, year, seq)
    if not keys:
        print("Nothing to archive.")
        return
    print(f"Archived {len(keys)} notes (before {cutoff.strftime('%Y-%m-%d')}).")


def cmd_tidy(args):
    """Run the retention sweep explicitly.

    The same policy `add` and session startup apply, exposed as a verb so a
    read command (`list`) never has to mutate state to keep the active view
    tidy. Safe to run any time; prints what it moved.
    """
    archived = policy.run_auto_archive(args.store)
    print(f"Tidied {archived} notes into the archive." if archived else "Nothing to tidy.")


