def cmd_learn(args):
    store = args.store
    content = check_length(content_from_args(args), MAX_CONTENT_LENGTH, "content", unit="bytes")
    brief_summary = (getattr(args, "brief_summary", "") or "").strip()
    check_length(brief_summary, BRIEF_SUMMARY_MAX, "--brief-summary")

    metadata = {}
    if getattr(args, "role", ""):
        metadata["role"] = args.role
    if getattr(args, "mission", ""):
        metadata["mission"] = args.mission

    tags = tag_list(args)
    areas = [a for a in (getattr(args, "area", None) or []) if a]
    tags, areas = infer.resolve(args, content, store, tags, areas)

    entry = store.add_learning(
        content=content,
        session_id=args.session_id or "",
        brief_summary=brief_summary,
        tags=tags,
        areas=areas,
        supersedes=(getattr(args, "supersedes", "") or "").strip() or None,
        **metadata,
    )
    print(f"Learned {_format_id(entry)}")


def cmd_learnings(args):
    store = args.store
    learnings = store.list_learnings(
        search=args.search, tag=getattr(args, "tag", None), area=getattr(args, "area", None)
    )
    learnings = _by_role_mission(args, learnings)

    if not learnings:
        print("No learnings found.")
        return
    if getattr(args, "index", False):
        for line in formatting.learnings_index(learnings):
            print(line)
        return
    for entry in learnings:
        if args.full:
            full = store.get_learning(entry["year"], entry["seq"])
            content = full.get("content", "") if full else entry.get("summary", "")
            print(f"{_format_id(entry)}: {content}")
        else:
            print(formatting.learning_line(entry))


def cmd_unlearn(args):
    _, year, seq = _learning_id_arg(args)
    if args.store.remove_learning(year, seq) is None:
        print(f"Learning {args.id} not found.", file=sys.stderr)
        sys.exit(1)
    print(f"Removed learning {args.id}.")


def cmd_archive_learning(args):
    """Archive a learning by ID. Parallels note archival but for the L- prefix.

    Exists so `/review-learnings` and hand-run cleanup can retire a stale
    learning without writing a replacement (which is what `supersede` is for).
    """
    _, year, seq = _learning_id_arg(args)
    if args.store.archive_learning(year, seq) is None:
        print(f"Learning {args.id} not found or already archived.", file=sys.stderr)
        sys.exit(1)
    print(f"Archived learning {args.id}.")


def cmd_supersede(args):
    """Archive an old learning and write a replacement pointing back at it.

    Frontmatter on the new learning carries ``supersedes: L-old`` so the
    lineage is visible when reading the .md.
    """
    if getattr(args, "content_file", None) is not None:
        args.content = content_from_args(args)
    store = args.store
    _, year, seq = _learning_id_arg(args)

    existing = store.get_learning(year, seq)
    if existing is None:
        print(f"Learning {args.id} not found.", file=sys.stderr)
        sys.exit(1)
    if existing.get("_from_archive"):
        die(f"{args.id} is already archived — cannot supersede.")

    content = check_length(args.content, MAX_CONTENT_LENGTH, "content", unit="bytes")
    tags = tag_list(args)
    areas = [a for a in (getattr(args, "area", None) or []) if a]
    tags, areas = infer.resolve(args, content, store, tags, areas)

    old_display_id = _format_id(existing)
    if store.archive_learning(year, seq) is None:
        die(f"failed to archive {args.id}.")

    metadata = {}
    if getattr(args, "role", ""):
        metadata["role"] = args.role
    if getattr(args, "mission", ""):
        metadata["mission"] = args.mission
    new_entry = store.add_learning(
        content=content,
        session_id=args.session_id or "",
        tags=tags,
        areas=areas,
        supersedes=old_display_id,
        **metadata,
    )
    print(f"Superseded {old_display_id} with {_format_id(new_entry)}")


