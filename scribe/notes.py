def _print_capped(lines: list) -> None:
    """Print at most ``_REPORT_LINE_CAP`` report lines, then a count of the rest.

    A repair over a four-year corpus can name thousands of entries; the cap
    keeps a terminal (and a hook's captured output) readable while still
    saying how much was elided.
    """
    for line in lines[:_REPORT_LINE_CAP]:
        print(line)
    if len(lines) > _REPORT_LINE_CAP:
        print(f"  ... and {len(lines) - _REPORT_LINE_CAP} more")


def _by_role_mission(args, rows: list) -> list:
    """Keep only rows matching ``--role``/``--mission`` when either is given.

    Case-insensitive, and an unset filter matches everything — including rows
    written before roles existed, which carry neither field.
    """
    for field in ("role", "mission"):
        wanted = getattr(args, field, None)
        if wanted:
            rows = [r for r in rows if r.get(field, "").lower() == wanted.lower()]
    return rows


def _parse_id_arg(raw: str, store=None) -> tuple:
    """Parse a ``TYPE-YEAR-seq`` ID argument; exit 1 on anything else."""
    parsed = formatting.parse_id(raw)
    if parsed is None:
        die(f"invalid ID: {raw.strip()}")
    return parsed


def _note_id_arg(args, *, reject: str) -> tuple:
    """Parse a note ID, rejecting learning IDs with a verb-specific message."""
    note_type, year, seq = _parse_id_arg(str(args.id))
    if note_type == "learning":
        die(f"{args.id} is a learning{reject}.")
    return note_type, year, seq


def _learning_id_arg(args) -> tuple:
    """Parse a learning ID, rejecting note IDs."""
    note_type, year, seq = _parse_id_arg(str(args.id))
    if note_type != "learning":
        die(f"{args.id} is a {note_type}, not a learning.")
    return note_type, year, seq


def _require_updated(updated, display_id: str):
    """Exit 1 when ``store.update_note`` reported that nothing was written.

    ``update_note`` is archive-aware, so ``None`` here means the note really
    is gone (deleted, or moved between the read and the write) — printing
    "Marked X as done." in that case is the failure fixed in Phase 1.5.
    """
    if updated is None:
        die(
            f"note {display_id} could not be updated — no matching index entry "
            "in the active or archive index. Run `notes.py repair`."
        )
    return updated


